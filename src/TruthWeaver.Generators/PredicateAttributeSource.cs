            internal sealed class PredicateAttribute : global::System.Attribute
            {
                /// <summary>Initializes a new instance of the <see cref="PredicateAttribute"/> class.</summary>
                /// <param name="name">The registered predicate name, as rule text writes it.</param>
                /// <param name="label">A short display name for the predicate.</param>
                /// <param name="description">What the predicate answers.</param>
                public PredicateAttribute(string name, string label, string description)
                {
                    this.Name = name;
                    this.Label = label;
                    this.Description = description;
                }

                /// <summary>Gets the registered predicate name.</summary>
                public string Name { get; }

                /// <summary>Gets the display name.</summary>
                public string Label { get; }

                /// <summary>Gets the description.</summary>
                public string Description { get; }
            }
        }

        """;
